import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ExcelJS from 'exceljs';
import { aggregateWarehouseProductReport } from '../src/lib/warehouse-sales-analytics.ts';
import { selectWarehouseReportRows, renderWarehouseSalesCsv, renderWarehouseSalesWorkbook } from '../src/lib/warehouse-sales-report-export.ts';

const lookup = new Map([['p1', { sku: '=danger', productName: 'Товар, "Казань"' }]]);
const sale = (warehouse, quantity, extra = {}) => ({ warehouse, quantity, price_with_disc: 100, is_return: false, product_id: 'p1', nm_id: 123, ...extra });
const rows = aggregateWarehouseProductReport([sale('Kazan', 2), sale('Kazan', 3), sale('Moscow', 1), sale('Kazan', 8, { is_return: true }), sale(null, 1, {product_id: null, nm_id: 999})], lookup);
assert.equal(rows.length, 3);
assert.equal(rows.reduce((n,r)=>n+r.units,0), 7);
assert.equal(rows.find(r=>r.warehouse==='Kazan').units, 5);
assert.equal(selectWarehouseReportRows(rows, 'Kazan', 'товар').length, 1);
assert.equal(selectWarehouseReportRows(rows, 'Kazan', 'missing').length, 0);
assert.equal(rows.find(r=>r.warehouse==='Unknown Warehouse').nmId, 999);
const csv = renderWarehouseSalesCsv(rows);
assert.ok(csv.startsWith('\uFEFFWarehouse'));
assert.ok(csv.includes("'=danger"));
assert.ok(csv.includes('"Товар, ""Казань"""'));
const scope = { from:'2026-08-31', to:'2026-09-27', marketplaceAccountId:'2', companyId:'2' };
const workbook = new ExcelJS.Workbook();
await workbook.xlsx.load(await renderWarehouseSalesWorkbook(rows, scope));
const details = workbook.getWorksheet('Warehouse Products');
assert.equal(details.rowCount, 4);
assert.equal(details.getCell('B2').type, ExcelJS.ValueType.String);
assert.equal(details.getCell('E2').type, ExcelJS.ValueType.Number);
assert.equal(workbook.getWorksheet('Warehouse Summary').getCell('B5').value, 7);
assert.equal(workbook.getWorksheet('Report Scope').getCell('B3').value, '2');
const empty = new ExcelJS.Workbook();
await empty.xlsx.load(await renderWarehouseSalesWorkbook([], scope));
assert.equal(empty.getWorksheet('Warehouse Products').rowCount, 1);
assert.equal(empty.getWorksheet('Warehouse Summary').getCell('B2').value, 0);
const route = readFileSync('src/app/api/inventory/warehouse-sales/export/route.ts','utf8');
assert.ok(route.indexOf('if (isAuthzFailure(authz)) return authz') < route.indexOf('await getWarehouseSalesAnalytics'));
assert.ok(route.includes('marketplaceAccountId: authz.marketplaceAccountId!'));
console.log('PASS: warehouse/product grouping, quantities, returns, unknown identities, filters, XLSX roundtrip, CSV injection, empty report and authorization order');
