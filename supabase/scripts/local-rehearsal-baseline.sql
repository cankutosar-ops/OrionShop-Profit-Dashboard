CREATE TABLE public.wb_sales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_date TIMESTAMPTZ, srid TEXT, nm_id BIGINT, quantity INTEGER DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT now(), product_id BIGINT REFERENCES public.products(id),
  revenue NUMERIC(12,2) NOT NULL DEFAULT 0, is_return BOOLEAN NOT NULL DEFAULT false,
