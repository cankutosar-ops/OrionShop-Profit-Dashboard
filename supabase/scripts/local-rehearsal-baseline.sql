CREATE TABLE public.brands (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL);
CREATE TABLE public.categories (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, parent_id BIGINT REFERENCES public.categories(id));
CREATE TABLE public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id BIGINT REFERENCES public.brands(id), category_id BIGINT REFERENCES public.categories(id),
  created_at TIMESTAMPTZ DEFAULT now(), supplier_article TEXT NOT NULL, name TEXT NOT NULL,
  nm_id BIGINT NOT NULL, barcode TEXT, marketplace_account_id BIGINT NOT NULL REFERENCES public.marketplace_accounts(id)
