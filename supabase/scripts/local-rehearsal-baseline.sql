CREATE OR REPLACE FUNCTION public.orion_jwt_company_ids() RETURNS BIGINT[] LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT COALESCE(ARRAY(SELECT DISTINCT value::BIGINT FROM jsonb_array_elements_text(COALESCE(auth.jwt()->'app_metadata'->'orion'->'company_ids', '[]')) AS t(value) WHERE value ~ '^[0-9]+$'), ARRAY[]::BIGINT[]);
$$;
CREATE OR REPLACE FUNCTION public.orion_jwt_marketplace_account_ids_claim() RETURNS BIGINT[] LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT COALESCE(ARRAY(SELECT DISTINCT value::BIGINT FROM jsonb_array_elements_text(COALESCE(auth.jwt()->'app_metadata'->'orion'->'marketplace_account_ids', '[]')) AS t(value) WHERE value ~ '^[0-9]+$'), ARRAY[]::BIGINT[]);
$$;
CREATE OR REPLACE FUNCTION public.orion_allowed_marketplace_account_ids() RETURNS BIGINT[] LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  WITH claimed AS (SELECT unnest(public.orion_jwt_marketplace_account_ids_claim()) AS id), by_company AS (
    SELECT ma.id FROM public.marketplace_accounts ma WHERE ma.company_id = ANY(public.orion_jwt_company_ids())
  ) SELECT COALESCE(ARRAY(SELECT DISTINCT id FROM by_company WHERE NOT EXISTS (SELECT 1 FROM claimed) OR id IN (SELECT id FROM claimed)), ARRAY[]::BIGINT[]);
$$;
REVOKE ALL ON FUNCTION public.orion_jwt_company_ids() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.orion_jwt_marketplace_account_ids_claim() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.orion_allowed_marketplace_account_ids() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.orion_jwt_company_ids(), public.orion_jwt_marketplace_account_ids_claim(), public.orion_allowed_marketplace_account_ids() TO authenticated, service_role;

