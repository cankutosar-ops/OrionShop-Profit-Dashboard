  created_at TIMESTAMPTZ DEFAULT now(), marketplace_account_id BIGINT NOT NULL REFERENCES public.marketplace_accounts(id),
  UNIQUE (product_id, tech_size, barcode)
);

CREATE TABLE public.wb_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_date TIMESTAMPTZ, srid TEXT, nm_id BIGINT, quantity INTEGER DEFAULT 1,
